"""Public sample reports: what a Flapp analysis actually looks like.

The conversion problem this exists for is written down elsewhere in this
codebase, in ``result_gating``: *a free result is a score with no angles and no
coaching to argue with*. Somebody deciding whether to sign up has no idea what
is behind the blur, and asking them to create an account to find out is asking
them to gamble. This page answers the question before the account.

It is built from FIXTURES generated by ``scripts/build_examples.py`` -- real
clips, run once through the real pipeline, trimmed and committed. Two reasons:
running MediaPipe on a crawler's request would be absurd, and more importantly
every number on this page is then a measurement of real footage rather than a
designer's placeholder. If a band moves or a scorer changes, the samples are
regenerated and the diff says what changed.

Deliberately NOT here: invented coaching prose. The samples carry the
deterministic half -- measurements, reference bands with their sources,
findings, the plan and the capture report -- which is the half that
distinguishes this product. A sample full of made-up coaching would be the one
thing on the page that is not real.

The page shell (SEO head, sidebar, footer, analytics) is imported from the
Academy renderer rather than copied. A second copy of that shell is how the
sidebar loses entries on one section and not another, which is a bug this
codebase has already fixed once.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
