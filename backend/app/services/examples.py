from typing import Any

from app.services.academy.renderer import SITE_NAME, _esc, _page

# backend/content/examples -- two levels up from app/services/, matching where
# the Academy keeps its own content.
CONTENT_DIR = Path(__file__).resolve().parents[2] / "content" / "examples"

# Display order on the hub. Video first: it is the product, and a photo sample
# leading would undersell what a clip buys.
ORDER = ("run-treadmill", "bike-road", "run-photo", "bike-aero")


@dataclass(frozen=True)
class Sample:
    slug: str
    title: str
    blurb: str
    mode: str
    sport: str
    data: dict[str, Any]

    # Video and photo results are different shapes, and the page should not
    # care: a video puts the score at the top level, a photo nests it under
    # ``score`` with a word for a grade ("Excellent") rather than a letter.
    @property
    def score(self) -> Any:
        if self.data.get("technique_score") is not None:
            return self.data["technique_score"]
        return (self.data.get("score") or {}).get("overall_score")

    @property
    def grade(self) -> Any:
        return (
            self.data.get("letter_grade")
            or (self.data.get("score") or {}).get("grade")
        )

    @property
    def keyframe(self) -> str | None:
        return self.data.get("keyframe_url")

    @property
    def kinogram(self) -> str | None:
        return self.data.get("kinogram_url")


@lru_cache(maxsize=1)
def load_samples() -> list[Sample]:
    """Every sample on disk, in display order. Cached for the process."""
    out: list[Sample] = []
    for slug in ORDER:
        path = CONTENT_DIR / f"{slug}.json"
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        out.append(Sample(
            slug=slug,
            title=data.get("title") or slug,
            blurb=data.get("blurb") or "",
            mode=data.get("mode") or "video",
            sport=data.get("sport_type") or data.get("sport") or "run",
            data=data,
        ))
    return out


def get_sample(slug: str) -> Sample | None:
    return next((s for s in load_samples() if s.slug == slug), None)


