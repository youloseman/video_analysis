# How each measurement is named and what it is measured in. The bands the API
# publishes carry the numbers and the citation but no unit, and a value printed
# without one reads as unfinished on a page whose whole job is looking
# finished. Nothing here invents data -- it labels it.
_FIELD_META: dict[str, tuple[str, str]] = {
    "knee_at_bdc": ("Knee at the bottom of the stroke", "°"),
    "knee_at_tdc": ("Knee at the top of the stroke", "°"),
    "hip_angle_avg": ("Hip angle", "°"),
    "elbow_angle_avg": ("Elbow angle", "°"),
    "trunk_angle_avg": ("Trunk angle", "°"),
    "shoulder_angle_avg": ("Shoulder angle", "°"),
    "forearm_tilt_avg": ("Forearm tilt", "°"),
    "head_alignment_avg": ("Head alignment", ""),
    "pelvic_ratio": ("Pelvic tilt ratio", ""),
    "cadence_spm": ("Cadence", " spm"),
    "trunk_lean_avg": ("Trunk lean", "°"),
    "ground_contact_ms": ("Ground contact", " ms"),
    "flight_time_ms": ("Flight time", " ms"),
    "overstride_ratio": ("Overstride", " × leg length"),
    "vertical_oscillation_m": ("Vertical oscillation", " m"),
}


def _label_unit(field: str, band: dict[str, Any]) -> tuple[str, str]:
    label, unit = _FIELD_META.get(field, ("", ""))
    return (
        band.get("label") or label or field.replace("_", " ").capitalize(),
        band.get("unit") or unit,
    )


def _num(v: Any, digits: int = 1) -> str:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return "—"
    return f"{f:.{digits}f}".rstrip("0").rstrip(".") if digits else f"{f:.0f}"


def _score_block(s: Sample) -> str:
    """The headline, and -- the point of this page -- what it was built from."""
    withheld = s.data.get("score_withheld")
    cov = s.data.get("score_coverage") or {}
    if withheld:
        head = (
            '<div class="ex-score ex-score-none"><span class="n">Not scored</span>'
            f'<p class="why">{_esc(withheld.get("detail") or "")}</p></div>'
        )
    else:
        head = (
            f'<div class="ex-score"><span class="n">{_esc(str(s.score))}'
            '<small>/100</small></span>'
            f'<span class="g">{_esc(str(s.grade or "—"))}</span></div>'
        )
    cov_line = ""
    if cov.get("measures_total"):
        scored, total = cov.get("measures_scored"), cov.get("measures_total")
        weight = cov.get("weight_covered")
        detail = ""
        if cov.get("excluded"):
            reasons = "; ".join(
                f"{_esc(k.replace('_', ' '))} — {_esc(str(v))}"
                for k, v in (cov.get("excluded") or {}).items()
            )
            detail = f'<span class="ex-cov-why">Not graded: {reasons}</span>'
        elif cov.get("missing"):
            detail = (
                '<span class="ex-cov-why">Not measurable on this clip: '
                + _esc(", ".join(m.replace("_", " ") for m in cov["missing"]))
                + "</span>"
            )
        cov_line = (
            f'<p class="ex-cov">Scored on <b>{scored}</b> of <b>{total}</b> '
            f"measures — {round((weight or 0) * 100)}% of the rubric.{detail}</p>"
        )
    return head + cov_line


def _bands_table(s: Sample) -> str:
    """Measurements against their reference bands, with the source named.

    This is the table the product is actually for, and the citation is why a
    reader should believe the band rather than take our word for it.
    """
    summary = s.data.get("sport_specific_metrics") or {}
    angles = s.data.get("angles") or {}

    # A photo carries its ranges alongside each angle instead of in a separate
    # reference_bands block. Normalised here so the table is written once.
    bands = s.data.get("reference_bands") or {}
    if not bands:
        bands = {
            key: {
                "low": ctx.get("optimal_min"), "high": ctx.get("optimal_max"),
                "label": ctx.get("label"), "unit": "°",
                "source": "", "value": ctx.get("value"),
            }
            for key, ctx in (s.data.get("angles_with_context") or {}).items()
            if isinstance(ctx, dict)
        }

    rows = []
    for field, band in bands.items():
        if not isinstance(band, dict):
            continue
        # `lo`/`hi` is what reference_bands actually publishes; `low`/`high`
        # is the photo path's normalised form above.
        lo = band.get("lo", band.get("low"))
        hi = band.get("hi", band.get("high"))
        value = band.get("value")
        if value is None:
            value = summary.get(field)
        if value is None:
            value = angles.get(field)
        if value is None or lo is None or hi is None:
            continue
        try:
            v = float(value)
        except (TypeError, ValueError):
            continue
        inside = float(lo) <= v <= float(hi)
        label, unit = _label_unit(field, band)
        rows.append(
            f'<tr class="{"ok" if inside else "out"}">'
            f'<td class="m">{_esc(label)}</td>'
            f'<td class="v">{_num(v)}{_esc(unit)}</td>'
            f'<td class="b">{_num(lo)}–{_num(hi)}{_esc(unit)}</td>'
            f'<td class="s">{_esc(band.get("source") or "")}</td>'
            "</tr>"
        )
    if not rows:
        return ""
    return (
        '<section class="ex-sec"><h2>Measured against published ranges</h2>'
        '<p class="ex-lede">Every target names where it comes from. A value a '
        "degree or two outside a band is inside the method&rsquo;s own error, "
        "not a finding.</p>"
        '<div class="ex-tw"><table class="ex-bands">'
        "<thead><tr><th>Measurement</th><th>Yours</th><th>Reference</th>"
        "<th>Source</th></tr></thead>"
        f"<tbody>{''.join(rows)}</tbody></table></div></section>"
    )


def _findings(s: Sample) -> str:
    issues = s.data.get("detected_issues") or []
    if not issues:
        return (
            '<section class="ex-sec"><h2>Findings</h2>'
            '<p class="ex-lede">Nothing outside its range on this clip.</p>'
            "</section>"
        )
    items = "".join(
        f'<li><b>{_esc(str(i.get("issue") or i.get("type") or "")).replace("_", " ")}'
        f'</b>{" — " + _esc(str(i.get("description") or i.get("message") or "")) if (i.get("description") or i.get("message")) else ""}</li>'
        for i in issues
    )
    return (
        f'<section class="ex-sec"><h2>Findings</h2><ul class="ex-list">{items}</ul>'
        "</section>"
    )


def _plan(s: Sample) -> str:
    """What to do next: bike adjustments, or running drills."""
    fit = (s.data.get("fit_plan") or {}).get("diagnostics") or []
    if fit:
        rows = "".join(
            f'<li><b>{_esc(str(d.get("component", "")).replace("_", " "))}</b>'
            f' — {_esc(str(d.get("reason") or ""))}</li>'
            for d in fit
        )
        return (
            '<section class="ex-sec"><h2>What to change on the bike</h2>'
            '<p class="ex-lede">In fitting order: each change moves the ones '
            "below it.</p>"
            f'<ol class="ex-list ex-num">{rows}</ol></section>'
        )
    plan = s.data.get("training_plan") or {}
    drills = plan.get("top_3_priorities") or []
    if not drills:
        return ""
    rows = "".join(
        f'<li><b>{_esc(str(d.get("drill") or d.get("title") or ""))}</b>'
        f'{" — " + _esc(str(d.get("cue") or d.get("why") or "")) if (d.get("cue") or d.get("why")) else ""}</li>'
        for d in drills
    )
    return (
        '<section class="ex-sec"><h2>What to work on</h2>'
        f'<ol class="ex-list ex-num">{rows}</ol></section>'
    )


def _capture(s: Sample) -> str:
    """How the recording itself limited the measurement -- the section nobody
    else in the category ships."""
    report = (s.data.get("sport_specific_metrics") or {}).get("capture_report") or {}
    checks = report.get("checks") or []
    if not checks:
        return ""
    rows = "".join(
        f'<tr class="c-{_esc(str(c.get("status")))}">'
        f'<td class="m">{_esc(str(c.get("label") or ""))}</td>'
        f'<td class="v">{_esc(str(c.get("measured") or ""))}</td>'
        f'<td class="b">{_esc(str(c.get("target") or ""))}</td></tr>'
        for c in checks
    )
    return (
        '<section class="ex-sec"><h2>What the recording cost the measurement</h2>'
        '<p class="ex-lede">Verdict: <b>'
        f'{_esc(str(report.get("verdict") or "—"))}</b>. Every analysis says how '
        "the clip limited it, and what to change next time.</p>"
        '<div class="ex-tw"><table class="ex-bands">'
        "<thead><tr><th>Check</th><th>Measured</th><th>Target</th></tr></thead>"
        f"<tbody>{rows}</tbody></table></div></section>"
    )


def _cta() -> str:
    return (
        '<section class="ex-cta"><h2>Film ten seconds and get your own</h2>'
        "<p>Side-on, phone upright, you filling the frame. Free account, no "
        "card.</p>"
        '<a class="ex-btn" href="/app">Analyze your form — free</a></section>'
    )


