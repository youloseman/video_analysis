def test_referenced_images_exist(samples):
    for s in samples:
        for url in (s.keyframe, s.kinogram):
            if not url:
                continue
            assert (MEDIA / Path(url).name).exists(), f"{url} is referenced and missing"


def test_images_are_light_enough_for_a_public_page(samples):
    """A 477 KB keyframe is fine inside a report somebody asked for and wrong
    on the page that has to load before they have decided to care."""
    for s in samples:
        for url in (s.keyframe, s.kinogram):
            if not url:
                continue
            path = MEDIA / Path(url).name
            size = path.stat().st_size
            assert size < 300_000, f"{path.name} is {size // 1024} KB"


def test_images_are_served(client, samples):
    url = next(s.keyframe for s in samples if s.keyframe)
    r = client.get(url)
    assert r.status_code == 200
    assert r.headers["content-type"].startswith("image/")


def test_webp_is_served_as_an_image_everywhere(client):
    """Found here, true site-wide: `mimetypes` seeds from the host, the host
    did not know webp, and EVERY webp on the site -- landing page, capture
    guide, samples -- went out as application/octet-stream. That loses CDN
    image handling and can make a browser offer a download instead of a
    picture. The types are registered explicitly now rather than looked up."""
    for url in ("/media/film-fill-run.webp", "/media/examples/run-treadmill.webp"):
        r = client.get(url)
        assert r.status_code == 200, url
        assert r.headers["content-type"] == "image/webp", url


def test_the_media_types_are_declared_not_inherited():
    import mimetypes

    for ext, expected in ((".webp", "image/webp"), (".woff2", "font/woff2")):
        assert mimetypes.guess_type("x" + ext)[0] == expected
