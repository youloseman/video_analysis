"""The public sample reports at /examples.

This page exists to answer a question the product otherwise cannot: a free
result is a score with no angles and no coaching to argue with, so somebody
deciding whether to sign up has no idea what is behind the blur. Asking them to
create an account to find out is asking them to gamble.

So the thing worth testing is not that HTML comes back. It is that what comes
back is REAL: numbers from a fixture generated by running actual footage
through the actual pipeline, reference bands with their sources, and no
invented prose anywhere. A sample report that quietly became a mock-up would
still render perfectly.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.main import app
from app.services import examples

CONTENT = Path(__file__).resolve().parents[1] / "content" / "examples"
MEDIA = Path(__file__).resolve().parents[1] / "app" / "static" / "media" / "examples"


@pytest.fixture(scope="module")
def client():
    with TestClient(app) as c:
        yield c


@pytest.fixture(scope="module")
def samples():
    return examples.load_samples()


# --------------------------------------------------------------------------
# the fixtures are real
# --------------------------------------------------------------------------

def test_every_advertised_sample_exists(samples):
    assert {s.slug for s in samples} == set(examples.ORDER), (
        "a sample is advertised in ORDER but has no fixture -- regenerate with "
        "`python scripts/build_examples.py`"
    )


@pytest.mark.parametrize("slug", examples.ORDER)
def test_a_sample_records_which_clip_it_came_from(slug):
    """Provenance, so a number on a public page can always be traced back to
    the footage that produced it."""
    data = json.loads((CONTENT / f"{slug}.json").read_text(encoding="utf-8"))
    assert data.get("source_clip"), f"{slug} does not say which clip it is"
    assert data.get("title") and data.get("blurb")


@pytest.mark.parametrize("slug", examples.ORDER)
def test_a_sample_carries_a_measurement(slug):
    data = json.loads((CONTENT / f"{slug}.json").read_text(encoding="utf-8"))
    has_bands = bool(data.get("reference_bands") or data.get("angles_with_context"))
    assert has_bands, f"{slug} has no reference ranges to show"


def test_no_sample_carries_invented_coaching(samples):
    """The page is built from the deterministic half on purpose. LLM prose
    would be the only thing on it that is not a measurement, and it would be
    frozen text presented as though it were written for that clip."""
    for s in samples:
        assert "ai_recommendations" not in s.data
        assert "coach_report" not in s.data


def test_fixtures_stay_small_enough_to_review(samples):
    """These are committed. A fixture nobody can read in a diff is a fixture
    nobody checks."""
    for s in samples:
        size = (CONTENT / f"{s.slug}.json").stat().st_size
        assert size < 60_000, f"{s.slug}.json is {size // 1024} KB"


